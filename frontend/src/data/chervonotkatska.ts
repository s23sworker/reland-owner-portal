import type { Room, Site } from '../mock'
import type { Polygon } from '../geometry'

/** Одиниць креслення на метр */
const S = 16

const poly = (points: Array<[number, number]>): Polygon =>
  points.map(([x, y]) => [Math.round(x * S), Math.round(y * S)])

const box = (x0: number, y0: number, x1: number, y1: number) =>
  poly([
    [x0, y0],
    [x1, y0],
    [x1, y1],
    [x0, y1],
  ])

